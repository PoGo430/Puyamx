"""Chip register header (<chip>.h) generated from the chip database.

Names follow the CMSIS / STM32 style so the code is easy to read:
    GPIOA->ODR, RCC->CR |= RCC_CR_HSION;  RCC_CFGR_HPRE_Pos / RCC_CFGR_HPRE_Msk
Instances that share a register layout share a type (GPIOA/GPIOB/GPIOF -> GPIO_TypeDef).
Also contains the tiny Cortex-M0+ core part (NVIC, SysTick, SCB, __WFI ...) so no CMSIS is needed.
"""
import json
import re

INSTANCE_RENAME = {"I2C": "I2C1", "LPTIM": "LPTIM1"}     # the database calls the single instance "I2C"


def _clean_reg(name):
    return re.sub(r"_(Input|Output)$", "", name, flags=re.I)


def groups(chip):
    """-> ordered {type_prefix: [instance names]} (instances with identical registers share a type)."""
    sig = {}
    order = []
    for name, p in chip.peripherals.items():
        key = json.dumps(p["regs"], sort_keys=True)
        if key not in sig:
            sig[key] = []
            order.append(key)
        sig[key].append(name)
    out = {}
    for key in order:
        names = sig[key]
        if len(names) > 1:
            pre = names[0]
            while pre and not all(n.startswith(pre) for n in names):
                pre = pre[:-1]
            pre = names[0] if (not pre or pre[-1].isdigit()) else pre      # TIM16/TIM17 -> TIM16, GPIOA/B/F -> GPIO
        else:
            pre = re.sub(r"\d+$", "", names[0]) if names[0] in ("SPI1", "USART1") else names[0]
        out[pre] = names
    return out


def macro_prefixes(chip):
    """{instance name: prefix used in the bit macros}  (GPIOB -> GPIO, USART2 -> USART, TIM17 -> TIM16)."""
    res = {}
    for pre, names in groups(chip).items():
        for n in names:
            res[INSTANCE_RENAME.get(n, n)] = pre
    return res


def _struct(prefix, regs):
    lines = [f"typedef struct {{"]
    items = {}
    for n, r in regs.items():
        items.setdefault(r["off"], (_clean_reg(n), r))
    pos = 0
    res = 0
    for off in sorted(items):
        name, _ = items[off]
        if off > pos:
            lines.append(f"    uint32_t RESERVED{res}[{(off - pos) // 4}];")
            res += 1
        lines.append(f"    volatile uint32_t {name};  /* 0x{off:03X} */")
        pos = off + 4
    lines.append(f"}} {prefix}_TypeDef;")
    return "\n".join(lines)


def generate(chip):
    d = chip.d
    o = []
    guard = f"{chip.id.upper()}_H"
    o.append(f"/* {chip.name} registers. Generated by Puya Studio from its chip database - do not edit.")
    o.append(" * Sources: " + "; ".join(s["doc"] for s in d["sources"]))
    o.append(" * Register offsets and reset values agree with the reference manual; the bit fields come from the")
    o.append(" * official Puya DFP SVD file. */")
    o.append(f"#ifndef {guard}\n#define {guard}\n")
    o.append("#include <stdint.h>\n")
    o.append(f"#define __{chip.id.upper()}__ 1")
    o.append(f"#define CHIP_NAME \"{chip.name}\"")
    o.append(f"#define CHIP_MAX_HZ {chip.max_hz}UL")
    o.append(f"#define FLASH_BASE 0x{chip.memory['flash_base']:08X}UL")
    o.append(f"#define SRAM_BASE 0x{chip.memory['ram_base']:08X}UL\n")
    # interrupts
    o.append("typedef enum {")
    o.append("    NonMaskableInt_IRQn = -14, HardFault_IRQn = -13, SVCall_IRQn = -5, PendSV_IRQn = -2, SysTick_IRQn = -1,")
    for n, name in sorted(chip.interrupts.items()):
        o.append(f"    {name}_IRQn = {n},")
    o.append("} IRQn_Type;\n")
    # structs, instances
    for prefix, names in groups(chip).items():
        o.append(_struct(prefix, chip.peripherals[names[0]]["regs"]))
    o.append("")
    for prefix, names in groups(chip).items():
        for n in names:
            inst = INSTANCE_RENAME.get(n, n)
            o.append(f"#define {inst} (({prefix}_TypeDef *) 0x{chip.peripherals[n]['base']:08X}UL)")
    o.append("")
    # bit fields
    for prefix, names in groups(chip).items():
        regs = chip.peripherals[names[0]]["regs"]
        for rn, r in sorted(regs.items(), key=lambda kv: kv[1]["off"]):
            rn2 = _clean_reg(rn)
            done = set()
            for fn, (lsb, w) in sorted(r["fields"].items(), key=lambda kv: kv[1][0]):
                if (fn) in done:
                    continue
                done.add(fn)
                base = f"{prefix}_{rn2}_{fn}"
                mask = ((1 << w) - 1) << lsb
                o.append(f"#define {base}_Pos ({lsb}U)")
                o.append(f"#define {base}_Msk (0x{mask:X}UL)")
                if w == 1:
                    o.append(f"#define {base} {base}_Msk")
    o.append("")
    # core peripherals
    o.append(CORE)
    o.append(f"\n#endif /* {guard} */\n")
    return "\n".join(o)


CORE = r"""/* ---- Cortex-M0+ core (NVIC, SysTick, SCB) and a few intrinsics ---- */
typedef struct { volatile uint32_t ISER; uint32_t R0[31]; volatile uint32_t ICER; uint32_t R1[31];
                 volatile uint32_t ISPR; uint32_t R2[31]; volatile uint32_t ICPR; uint32_t R3[31];
                 uint32_t R4[64]; volatile uint32_t IP[8]; } NVIC_Type;
typedef struct { volatile uint32_t CTRL, LOAD, VAL; volatile const uint32_t CALIB; } SysTick_Type;
typedef struct { volatile const uint32_t CPUID; volatile uint32_t ICSR; uint32_t R0; volatile uint32_t AIRCR;
                 volatile uint32_t SCR; volatile const uint32_t CCR; uint32_t R1; volatile uint32_t SHP[2]; } SCB_Type;
#define NVIC ((NVIC_Type *) 0xE000E100UL)
#define SysTick ((SysTick_Type *) 0xE000E010UL)
#define SCB ((SCB_Type *) 0xE000ED00UL)
#define SysTick_CTRL_ENABLE_Msk 1UL
#define SysTick_CTRL_TICKINT_Msk 2UL
#define SysTick_CTRL_CLKSOURCE_Msk 4UL
#define SCB_SCR_SLEEPDEEP_Msk 4UL
#define SCB_SCR_SLEEPONEXIT_Msk 2UL

static inline void __enable_irq(void) { __asm volatile ("cpsie i" ::: "memory"); }
static inline void __disable_irq(void) { __asm volatile ("cpsid i" ::: "memory"); }
static inline void __WFI(void) { __asm volatile ("wfi"); }
static inline void __WFE(void) { __asm volatile ("wfe"); }
static inline void __NOP(void) { __asm volatile ("nop"); }
static inline void __DSB(void) { __asm volatile ("dsb 0xF" ::: "memory"); }
static inline void __ISB(void) { __asm volatile ("isb 0xF" ::: "memory"); }
static inline void NVIC_EnableIRQ(IRQn_Type n) { NVIC->ISER = 1UL << ((uint32_t) n & 31U); }
static inline void NVIC_DisableIRQ(IRQn_Type n) { NVIC->ICER = 1UL << ((uint32_t) n & 31U); }
static inline void NVIC_ClearPendingIRQ(IRQn_Type n) { NVIC->ICPR = 1UL << ((uint32_t) n & 31U); }
static inline void NVIC_SetPriority(IRQn_Type n, uint32_t prio)   /* prio 0..3 (2 bits) */
{
    if ((int32_t) n >= 0) {
        uint32_t i = ((uint32_t) n) >> 2, s = (((uint32_t) n) & 3U) * 8U + 6U;
        NVIC->IP[i] = (NVIC->IP[i] & ~(0xFFUL << ((((uint32_t) n) & 3U) * 8U))) | ((prio & 3UL) << s);
    }
}
"""
